"""
HW5 Part 3 step 18 - write reports/hw05/TOOL_CONTRACTS.md.

    python code/tool_contracts.py        # make contracts

For each of the three domain tools the document shows:
  - the expected JSON input schema   (generated from the Pydantic model)
  - the rejected JSON input          (the Part 2B call, read from the raw capture)
  - the returned error output        (the envelope the server sent back)
  - why the call was rejected

Nothing is typed in by hand except the "why": the schema comes from
domain_tools.py and the rejected calls come from
reports/hw05/raw/mcp_inspector_domain.json, so this file cannot drift away
from what the code does and what the Inspector recorded.
"""
import json
from pathlib import Path

from domain_tools import INPUT_MODELS, input_schema

ROOT = Path(__file__).resolve().parent.parent
CAPTURE = ROOT / "reports" / "hw05" / "raw" / "mcp_inspector_domain.json"
OUT_FILE = ROOT / "reports" / "hw05" / "TOOL_CONTRACTS.md"

WHY = {
    "search_notices": (
        "`limit` is declared as an integer from 1 to 20 (`minimum: 1`, `maximum: 20`). "
        "The call sent 500, which is above the maximum. The cap exists so that one call "
        "cannot pull a large part of the 5,000-row table into a model's context. "
        "The check runs before any SQL, so the database was never queried."
    ),
    "get_notice": (
        "`recall_number` must match the pattern `^F-\\d{4}-\\d{4}$` (F, four digits, a "
        "four-digit year, e.g. F-0001-2025). `ABC-12` does not start with `F-` and has "
        "neither digit group, so it cannot be a recall number. Rejecting it here tells "
        "the caller the expected format instead of answering \"not found\" after a lookup."
    ),
    "recall_summary": (
        "`group_by` is an enum with four allowed values: category, state, year, firm. "
        "`color` is not one of them and no such column exists. Because only these four "
        "values are accepted, the value is never free text that reaches the SQL."
    ),
}


def block(obj) -> str:
    return "```json\n" + json.dumps(obj, indent=2) + "\n```"


def main():
    capture = json.loads(CAPTURE.read_text(encoding="utf-8"))
    # the rejected call of each tool = the captured call whose envelope says ok: false
    rejected = {}
    for call in capture["calls"]:
        envelope = call["result"].get("structuredContent") or {}
        if envelope.get("ok") is False:
            rejected[call["tool"]] = (call["arguments"], envelope)

    lines = [
        "# HW5 Part 3 - Tool contracts and rejected calls",
        "",
        "Generated by `python code/tool_contracts.py`. The schemas come from the Pydantic",
        "models in `code/domain_tools.py`; the rejected inputs and error outputs are the",
        f"Part 2B calls recorded in `reports/hw05/raw/{CAPTURE.name}`",
        f"(captured {capture['captured_at']}).",
        "",
        "Every tool returns the same envelope. A rejected call is not an exception:",
        "",
        block({"ok": False, "data": None, "error": "<field>: <reason>"}),
        "",
    ]
    for number, name in enumerate(INPUT_MODELS, start=1):
        arguments, envelope = rejected[name]
        lines += [
            f"## {number}. {name}",
            "",
            "**Expected JSON input schema**",
            "",
            block(input_schema(name)),
            "",
            "**Rejected JSON input** (Part 2B)",
            "",
            block(arguments),
            "",
            "**Returned error output**",
            "",
            block(envelope),
            "",
            "**Why it was rejected**",
            "",
            WHY[name],
            "",
        ]
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_FILE.relative_to(ROOT)}")
    for name, (arguments, envelope) in rejected.items():
        print(f"  {name}: {json.dumps(arguments)} -> {envelope['error']}")


if __name__ == "__main__":
    main()
